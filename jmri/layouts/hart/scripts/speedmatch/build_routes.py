#!/usr/bin/env python3
"""Write speedmatch/routes.json: each test route's (block sensor, block) pairs, from tables.xml.

    python3 jmri/layouts/hart/scripts/speedmatch/build_routes.py          # rewrite routes.json
    python3 jmri/layouts/hart/scripts/speedmatch/build_routes.py --check  # exit 1 if it is stale

The running order of each route is typed once, as ROUTE_BLOCKS and ROUTE_MID_BLOCK in
analyze.py (read here with ast, so analyze.py is not imported). Each block's sensor is the
<occupancysensor> tables.xml gives it. analyze.py reads routes.json with the standard
library only, because the Pi's speed-match live publisher has neither hartlib nor tables.xml.

After a block or sensor rename (PanelPro, then make tables-pull), --check fails here:
rebuild, and convert speed-match logs recorded before the rename, as
rename_extension_tracks.py did for the 2026-11-13 extension tracks.
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(p / "tools/hartlib/src") for p in HERE.parents
                if (p / "tools/hartlib/src").is_dir()][:1] or sys.exit(f"no tools/hartlib/src above {__file__}")
from hartlib import paths, tables  # noqa: E402

ANALYZE = HERE / "analyze.py"
OUT = HERE / "routes.json"


def route_order(source: Path = ANALYZE) -> tuple[dict[str, list[str]], dict[str, str]]:
    """(ROUTE_BLOCKS, ROUTE_MID_BLOCK) as analyze.py types them."""
    found = {}
    for node in ast.parse(source.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("ROUTE_BLOCKS", "ROUTE_MID_BLOCK"):
                found[node.targets[0].id] = ast.literal_eval(node.value)
    missing = {"ROUTE_BLOCKS", "ROUTE_MID_BLOCK"} - set(found)
    if missing:
        raise SystemExit(f"{paths.rel(source)} has no {', '.join(sorted(missing))}")
    return found["ROUTE_BLOCKS"], found["ROUTE_MID_BLOCK"]


def block_sensors(root) -> dict[str, str]:
    """Block user name -> its occupancy sensor user name (the full <block>)."""
    out = {}
    for b in tables.blocks(root):
        name, sensor = tables.user_name(b), tables.text(b, "occupancysensor")
        if name and sensor:
            out[name] = sensor
    return out


def build(root, order: dict[str, list[str]], mid: dict[str, str]) -> dict:
    sensors = block_sensors(root)
    missing = sorted({b for blocks in order.values() for b in blocks} - set(sensors))
    if missing:
        raise SystemExit("speed-match route block(s) with no occupancy sensor in %s: %s"
                         % (paths.rel(paths.TABLES_XML), ", ".join(missing)))
    for route, block in mid.items():
        if block not in order.get(route, []):
            raise SystemExit(f"ROUTE_MID_BLOCK[{route!r}] = {block!r} is not on that route")
    return {
        "_comment": "Generated by build_routes.py from tables.xml and analyze.py ROUTE_BLOCKS; "
                    "do not edit. Each route is [block sensor, block] in running order.",
        "routes": {r: [[sensors[b], b] for b in blocks] for r, blocks in order.items()},
        "mid": {r: sensors[b] for r, b in mid.items()},
    }


def render(data: dict) -> str:
    """JSON with one [sensor, block] pair per line, so a rename is a one-line diff."""
    dump = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    routes = ",\n".join(
        f"  {dump(r)}: [\n" + ",\n".join(f"   {dump(pair)}" for pair in pairs) + "\n  ]"
        for r, pairs in data["routes"].items())
    mid = ",\n".join(f"  {dump(r)}: {dump(s)}" for r, s in data["mid"].items())
    return (f'{{\n "_comment": {dump(data["_comment"])},\n "routes": {{\n{routes}\n }},\n'
            f' "mid": {{\n{mid}\n }}\n}}\n')


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if routes.json is stale; write nothing")
    args = ap.parse_args(argv)
    text = render(build(tables.read(paths.TABLES_XML), *route_order()))
    current = OUT.read_text(encoding="utf-8") if OUT.is_file() else None
    if args.check:
        if current != text:
            print(f"{paths.rel(OUT)} is stale; run {paths.rel(Path(__file__))} "
                  "(and convert speed-match logs recorded before a rename)")
            return 1
        print(f"{paths.rel(OUT)} is current")
        return 0
    if current != text:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {paths.rel(OUT)}")
    else:
        print(f"{paths.rel(OUT)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
