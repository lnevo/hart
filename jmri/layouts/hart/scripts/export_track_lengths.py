#!/usr/bin/env python3
"""Write docs/jmri/TRACK_LENGTHS.md from data/block_lengths.csv and check it
against the block lengths in output/tables.xml.

The CSV is the record (inches, as measured/estimated on the railroad);
tables.xml carries the same values in mm for Dispatcher. Run with --check to
fail on drift between the two or a stale document.
"""
import csv, sys
from pathlib import Path

sys.path[:0] = [str(p / "tools/hartlib/src") for p in Path(__file__).resolve().parents
                if (p / "tools/hartlib/src").is_dir()][:1] or sys.exit(f"no tools/hartlib/src above {__file__}")
from hartlib import paths, tables  # noqa: E402

ROOT = paths.REPO_ROOT
CSV = paths.LAYOUT_DATA / "block_lengths.csv"
TABLES = paths.TABLES_XML
DOC = ROOT / "docs/jmri/TRACK_LENGTHS.md"
MM = 25.4


def table_lengths():
    """Block userName -> length in mm, for blocks that have both."""
    return {
        tables.user_name(b): float(b.get("length"))
        for b in tables.blocks(tables.read(TABLES))
        if b.get("length") and tables.user_name(b)
    }


def render(rows):
    def fmt(r):
        i = float(r["inches"])
        return f"| {r['user_name']} | {r['occupancy_sensor']} | {i:g} | {i * MM:.1f} | {r['flag']} | {r['old_source']} |"
    head = "| Block | Occupancy sensor | Inches | mm | Basis | Note |\n|---|---|---|---|---|---|"
    tracks = [r for r in rows if r["user_name"].startswith("Track ") and r["flag"] != "stub"]
    stubs = [r for r in rows if r["flag"] == "stub"]
    osb = [r for r in rows if r["user_name"].startswith("OS ")]
    return f"""# Track and spur lengths

Generated by `jmri/layouts/hart/scripts/export_track_lengths.py` from
`jmri/layouts/hart/data/block_lengths.csv`. Do not edit by hand; change the CSV.

Dispatcher takes the shortest path by block length and uses these for stopping
distances and train length checks. JMRI stores them in millimetres in the block
`length` attribute of `output/tables.xml`; the CSV is the record in inches, and
`--check` fails if the two disagree (`./tools/check.sh` runs it).

**Basis:** `assigned` = measured or carried over from the old layout;
`estimate` = placeholder to refine; `cut` = remainder after OS blocks were cut
from it; `split` = one long block divided evenly; `stub` = hidden throat block
sharing the detector of its track (the track's own row carries the real length).

## Tracks and spurs

{head}
{chr(10).join(fmt(r) for r in tracks)}

## Hidden throat stubs

{head}
{chr(10).join(fmt(r) for r in stubs)}

## Switch (OS) blocks

{head}
{chr(10).join(fmt(r) for r in osb)}
"""


def main():
    rows = list(csv.DictReader(CSV.open(encoding="utf-8")))
    text = render(rows)
    if "--check" not in sys.argv:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)} ({len(rows)} blocks)")
        return 0
    bad = []
    tl = table_lengths()
    for r in rows:
        v = tl.get(r["user_name"])
        if v is None or abs(v - float(r["inches"]) * MM) > 1.0:
            bad.append(f"{r['user_name']}: csv {float(r['inches']) * MM:.1f} mm, tables {v}")
    bad += [f"{k}: in tables.xml ({v} mm) but not in CSV" for k, v in tl.items()
            if k not in {r["user_name"] for r in rows}]
    if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
        bad.append("docs/jmri/TRACK_LENGTHS.md is stale; run the script without --check")
    print("\n".join(bad) or "track lengths OK")
    return 1 if bad else 0


sys.exit(main())
