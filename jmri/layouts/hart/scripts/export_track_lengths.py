#!/usr/bin/env python3
"""Write docs/jmri/TRACK_LENGTHS.md from data/block_lengths.csv and check it
against the block lengths in output/tables.xml.

    export_track_lengths.py            # write the document
    export_track_lengths.py --tables   # set the staging block lengths in tables.xml (JMRI closed)
    export_track_lengths.py --check    # exit 1 on drift between the two, or a stale document

The CSV is the record: each block's AnyRail plan 5.3c length (plan_in) and, for a
timed block, its measured length (measured_in). JMRI's block holds the measured
length where there is one, else the plan length (hartlib BlockLength.jmri_in), in mm.
"""
import csv, sys
from pathlib import Path

sys.path[:0] = [str(p / "tools/hartlib/src") for p in Path(__file__).resolve().parents
                if (p / "tools/hartlib/src").is_dir()][:1] or sys.exit(f"no tools/hartlib/src above {__file__}")
from hartlib import paths, railroad, tables  # noqa: E402

ROOT = paths.REPO_ROOT
CSV = paths.LAYOUT_DATA / "block_lengths.csv"
TABLES = paths.TABLES_XML
DOC = ROOT / "docs/jmri/TRACK_LENGTHS.md"
MM = 25.4


# The main and upper levels' blocks stand on internal system names (IB:C3:...) until they are imported, with
# their plan lengths from the device map (build_layout_le.py): not measured yet, so not in the CSV, and not checked.
PLAN_BLOCKS = "IB:C3:"


def table_lengths():
    """Block userName -> length in mm, for blocks that have both, but the main and upper plan blocks (PLAN_BLOCKS)."""
    return {
        tables.user_name(b): float(b.get("length"))
        for b in tables.blocks(tables.read(TABLES))
        if b.get("length") and tables.user_name(b) and not tables.system_name(b).startswith(PLAN_BLOCKS)
    }


def render(rows):
    def fmt(b):
        measured = f"{b.measured_in:g}" if b.measured_in is not None else ""
        return (f"| {b.user_name} | {b.occupancy_sensor} | {b.plan_in:g} | {measured} | {b.source} | "
                f"{b.jmri_in * MM:.1f} | {notes[b.user_name]} |")
    notes = {r["user_name"]: r["note"] for r in csv.DictReader(CSV.open(encoding="utf-8"))}
    head = ("| Block | Occupancy sensor | Plan in | Measured in | JMRI length from | JMRI mm | Note |\n"
            "|---|---|---|---|---|---|---|")
    tracks = [b for b in rows.values() if b.user_name.startswith("Track ")]
    osb = [b for b in rows.values() if b.user_name.startswith("OS ")]
    return f"""# Track and spur lengths

Generated by `jmri/layouts/hart/scripts/export_track_lengths.py` from
`jmri/layouts/hart/data/block_lengths.csv`. Do not edit by hand; change the CSV.

Dispatcher takes the shortest path by block length and uses these for stopping
distances and train length checks. JMRI stores them in millimetres in the block
`length` attribute of `output/tables.xml`, and `--check` fails if the two disagree
(`./tools/check.sh` runs it).

**Plan in** is the block's length in the AnyRail plan 5.3c, written by
`tools/schematic/plan_lengths.py`: a track block's run between the turnout ends,
an OS block its turnout's product length from the points to the frog end. The
schematic, the Layout Editor panel and the signal rules use it alone.
**Measured in** is the timed length (`source` `timed`: the block's timed share of
the test loop, or timed passes; `infer_block_lengths.py`, method in
`docs/jmri/speedmatching/ANYRAIL_LENGTHS.md`), kept for speed profiling and JMRI.
JMRI's length is the measured one where there is one, else the plan length.

## Tracks and spurs

{head}
{chr(10).join(fmt(b) for b in tracks)}

## Switch (OS) blocks

{head}
{chr(10).join(fmt(b) for b in osb)}
"""


def set_tables(rows) -> int:
    """Set each CSV block's length in tables.xml to its JMRI length (mm); returns how many changed. Stops on a block
    tables.xml does not hold, or while JMRI runs (a Store would undo it)."""
    if tables.jmri_running():
        sys.exit("JMRI is running: quit PanelPro and CATS first (a Store would undo this)")
    t = tables.load(TABLES)
    full = {tables.user_name(b): b for b in tables.blocks(t.root) if tables.user_name(b)}
    missing = sorted(set(rows) - set(full))
    if missing:
        sys.exit(f"blocks not in {paths.rel(TABLES)}: {missing}")
    changed = 0
    for name, b in rows.items():
        want = f"{b.jmri_in * MM:.1f}"
        if full[name].get("length") != want:
            full[name].set("length", want)
            changed += 1
    t.save()
    return changed


def main():
    try:
        rows = railroad.read_block_lengths(CSV)
    except railroad.FactsError as exc:
        sys.exit(str(exc))
    text = render(rows)
    if "--tables" in sys.argv:
        paths.exit_if_overridden(Path(__file__).name)
        print(f"set {set_tables(rows)} block lengths in {paths.rel(TABLES)}")
        return 0
    if "--check" not in sys.argv:
        paths.exit_if_overridden(Path(__file__).name)
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)} ({len(rows)} blocks)")
        return 0
    bad = []
    tl = table_lengths()
    for name, b in rows.items():
        v = tl.get(name)
        if v is None or abs(v - b.jmri_in * MM) > 1.0:
            bad.append(f"{name}: csv {b.jmri_in * MM:.1f} mm ({b.source}), tables {v}; run with --tables")
    bad += [f"{k}: in tables.xml ({v} mm) but not in CSV" for k, v in tl.items() if k not in rows]
    if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
        bad.append("docs/jmri/TRACK_LENGTHS.md is stale; run the script without --check")
    print("\n".join(bad) or "track lengths OK")
    return 1 if bad else 0


sys.exit(main())
