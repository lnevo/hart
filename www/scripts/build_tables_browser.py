#!/usr/bin/env python3
"""Write the tables file page and its browser data from the JMRI tables file.

    python3 www/scripts/build_tables_browser.py          # write both
    python3 www/scripts/build_tables_browser.py --check  # exit 1 if the page is stale or the data fails a check

Writes www/data/tables-browser.json (the browser's rows) and fills the marked
regions of www/behind/tables-file.html (its numbers, version and excerpts; see
tables_page.py). prepare_github_pages.py runs the same fill on every site build.

The page is committed; the JSON is not (ADR-036): the site build and the local preview build it with
data_text() (site_views.py), and --check builds it in memory and checks it (problems()).

Allowlist only: each table lists the fields it emits. File history,
connections and paths are never read into the output. Output is in file order
with no timestamps.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections.abc import Callable
from pathlib import Path
from typing import TypedDict

sys.path[:0] = [str(p / "tools/hartlib/src") for p in Path(__file__).resolve().parents
                if (p / "tools/hartlib/src").is_dir()][:1] or sys.exit(f"no tools/hartlib/src above {__file__}")
from hartlib import paths, tables  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tables_page  # noqa: E402

ROOT = paths.REPO_ROOT
SRC = paths.TABLES_XML
OUT_REL = Path("data/tables-browser.json")
PAGE_REL = Path("behind/tables-file.html")
WWW = ROOT / "www"
OUT = WWW / OUT_REL

NOTE = "Generated by www/scripts/build_tables_browser.py from the tables file; do not edit by hand."


class BrowserDataError(Exception):
    """The browser data cannot be built from the tables file, or fails a check; the message says why."""


MAST_RE = re.compile(r"\$(shsm|vsm):([^:]+):([^(]+)\(")
FEEDBACK = {"TWOSENSOR": "Two sensors", "DIRECT": "Direct", "ONESENSOR": "One sensor", "MONITORING": "Monitoring",
            "DELAYED": "Delayed", "EXACT": "Exact", "INDIRECT": "Indirect"}
SECTION_MADE = {"signalmastlogic": "From a mast pair", "userdefined": "Defined by hand"}

Cell = str | int
Row = list[Cell]


class Column(TypedDict):
    k: str
    label: str


class Table(TypedDict):
    id: str
    label: str
    cols: list[Column]
    rows: list[Row]


def names(e: ET.Element) -> list[str]:
    """[system name, user name], as the file writes them (not stripped)."""
    return [e.findtext("systemName", ""), e.findtext("userName", "") or ""]


def named(e: ET.Element) -> list[Cell]:
    """names(e) as the start of a row, which may go on with counts."""
    return list(names(e))


def yes(v: str | None) -> str:
    return "yes" if (v or "").strip().lower() == "yes" else "no"


def note(e: ET.Element) -> str:
    """An object's comment. JMRI stores it as a child element or an attribute."""
    return (e.findtext("comment") or e.get("comment") or "").strip()


def load(src: Path | str = SRC) -> tuple[bytes, ET.Element]:
    """The tables file's bytes and its root, parsed by hartlib.tables."""
    try:
        raw = Path(src).read_bytes()
        return raw, tables.loads(raw, Path(src)).root
    except OSError as err:
        raise BrowserDataError(f"cannot read the tables file {src}: {err.strerror or err}") from err
    except (ET.ParseError, ValueError) as err:
        raise BrowserDataError(f"the tables file {src} is not XML: {err}") from err


# —— One function per table: its rows, in file order ——

def sensor_rows(r: ET.Element) -> list[Row]:
    """Sensors: MQTT or internal, from the system name prefix."""
    return [named(e) + ["MQTT" if names(e)[0].startswith("M2S") else "Internal", note(e)] for e in tables.sensors(r)]


def turnout_rows(r: ET.Element) -> list[Row]:
    rows: list[Row] = []
    for e in tables.turnouts(r):
        fb = FEEDBACK.get(e.get("feedback", ""), e.get("feedback", ""))
        sens = ", ".join(x for x in (e.get("sensor1"), e.get("sensor2")) if x)
        rows.append(named(e) + [fb, sens, note(e)])
    return rows


def memory_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [note(e)] for e in tables.section(r, "memories", "memory")]


def head_rows(r: ET.Element) -> list[Row]:
    rows: list[Row] = []
    for e in tables.signal_heads(r):
        cls = e.get("class", "").rsplit(".", 1)[-1]
        rows.append(named(e) + ["Virtual" if cls.startswith("Virtual") else cls.replace("Xml", ""), note(e)])
    return rows


def mast_rows(r: ET.Element) -> list[Row]:
    rows: list[Row] = []
    for e in tables.masts(r):
        s = names(e)[0]
        m = MAST_RE.search(s)
        kind = ("On heads" if m.group(1) == "shsm" else "Virtual") if m else ""
        rows.append(named(e) + [kind, m.group(2) if m else "", m.group(3) if m else "", note(e)])
    return rows


def block_rows(r: ET.Element) -> list[Row]:
    """Blocks: the second, full pass only (the first pass lists names)."""
    return [named(e) + [e.get("length", ""), e.findtext("occupancysensor", "") or "", len(e.findall("path")), note(e)]
            for e in tables.blocks(r)]


def layout_block_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [e.get("occupancysensor", "")] for e in tables.layout_blocks(r)]


def section_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [SECTION_MADE.get(e.get("creationtype", ""), e.get("creationtype", "")),
                        len(e.findall("blockentry"))] for e in tables.section(r, "sections", "section")]


def transit_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [len(e.findall("transitsection"))] for e in tables.section(r, "transits", "transit")]


def route_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [e.get("controlTurnout", ""), len(e.findall("routeOutputTurnout")), note(e)]
            for e in tables.section(r, "routes", "route")]


def sml_rows(r: ET.Element) -> list[Row]:
    """One row per source and destination mast pair."""
    return [[e.findtext("sourceSignalMast", ""), d.findtext("destinationSignalMast", ""), yes(d.findtext("enabled")),
             note(d)] for e in tables.section(r, "signalmastlogics", "signalmastlogic") for d in e.findall("destinationMast")]


def entry_exit_rows(r: ET.Element) -> list[Row]:
    return [[s.get("item", ""), d.get("item", "")] for ee in r.findall("entryexitpairs")
            for p in ee.findall("layoutPanel") for s in p.findall("source") for d in s.findall("destination")]


def logix_rows(r: ET.Element) -> list[Row]:
    return [named(e) + [yes(e.get("enabled")), len(e.findall("logixConditional"))]
            for e in tables.section(r, "logixs", "logix")]


def logixng_rows(r: ET.Element) -> list[Row]:
    rows: list[Row] = []
    for e in tables.section(r, "LogixNGs", "LogixNG"):
        cn = e.find("ConditionalNGs")
        rows.append(named(e) + [yes(e.get("enabled")), len(cn.findall("systemName")) if cn is not None else 0])
    return rows


NAMES = (("sys", "System name"), ("user", "User name"))
# (id, label, columns, rows, its count in meta); the page and the browser show the tables in this order.
TABLES: tuple[tuple[str, str, tuple[tuple[str, str], ...], Callable[[ET.Element], list[Row]], str], ...] = (
    ("sensors", "Sensors", NAMES + (("kind", "Kind"), ("note", "Comment")), sensor_rows, "sensors"),
    ("turnouts", "Turnouts", NAMES + (("fb", "Feedback"), ("sens", "Feedback sensors"), ("note", "Comment")),
     turnout_rows, "turnouts"),
    ("memories", "Memories", NAMES + (("note", "Comment"),), memory_rows, "memories"),
    ("heads", "Signal heads", NAMES + (("type", "Head type"), ("note", "Comment")), head_rows, "heads"),
    ("masts", "Signal masts", NAMES + (("kind", "Heads"), ("app", "Appearance system"), ("shape", "Mast type"),
                                       ("note", "Comment")), mast_rows, "masts"),
    ("blocks", "Blocks", NAMES + (("len", "Length (mm)"), ("occ", "Occupancy sensor"), ("paths", "Paths"),
                                  ("note", "Comment")), block_rows, "blocks"),
    ("layoutblocks", "Layout blocks", NAMES + (("occ", "Occupancy sensor"),), layout_block_rows, "layoutBlocks"),
    ("sections", "Sections", NAMES + (("made", "How made"), ("blocks", "Blocks listed")), section_rows, "sections"),
    ("transits", "Transits", NAMES + (("secs", "Sections"),), transit_rows, "transits"),
    ("routes", "Routes", NAMES + (("ctl", "Control turnout"), ("outs", "Turnout settings"), ("note", "Comment")),
     route_rows, "routes"),
    ("sml", "Signal Mast Logic", (("src", "Source mast"), ("dst", "Destination mast"), ("on", "Enabled"),
                                  ("note", "Comment")), sml_rows, "smlDestinations"),
    ("entryexit", "Entry/Exit", (("src", "Source"), ("dst", "Destination")), entry_exit_rows, "entryExit"),
    ("logix", "Logix", NAMES + (("on", "Enabled"), ("conds", "Conditionals")), logix_rows, "logix"),
    ("logixng", "LogixNG", NAMES + (("on", "Enabled"), ("conds", "ConditionalNGs")), logixng_rows, "logixng"),
)
# meta's keys in the order the JSON writes them; smlSources counts mast logic sources, not a table.
META_ORDER = ("sensors", "turnouts", "memories", "heads", "masts", "smlSources", "smlDestinations", "blocks",
              "layoutBlocks", "sections", "transits", "routes", "entryExit", "logix", "logixng")


def build(r: ET.Element) -> dict:
    """The browser data: every table's rows and the counts the page quotes."""
    out: list[Table] = []
    counts: dict[str, int] = {"smlSources": len(tables.section(r, "signalmastlogics", "signalmastlogic"))}
    for tid, label, cols, rows_of, meta_key in TABLES:
        rows = rows_of(r)
        out.append({"id": tid, "label": label, "cols": [{"k": k, "label": lab} for k, lab in cols], "rows": rows})
        counts[meta_key] = len(rows)
    return {"_note": NOTE, "meta": {k: counts[k] for k in META_ORDER}, "tables": out}


# Tables every real tables file fills; an empty one means the file or the reader is broken.
REQUIRED = ("sensors", "turnouts", "masts", "blocks")


def problems(data: dict) -> list[str]:
    """What is wrong with built browser data: a required table with no rows, a row whose width is not its table's,
    or counts in meta that are not the tables' row counts."""
    out = []
    by = {t.get("id"): t for t in data.get("tables") or []}
    for tid in REQUIRED:
        if not (by.get(tid) or {}).get("rows"):
            out.append(f"table {tid!r} has no rows")
    for tid, t in by.items():
        width = len(t.get("cols") or [])
        bad = sum(1 for row in t.get("rows") or [] if len(row) != width)
        if bad:
            out.append(f"table {tid!r}: {bad} rows are not {width} fields wide")
    meta = data.get("meta") or {}
    for tid in REQUIRED:  # meta names these four as their tables do
        if tid in by and meta.get(tid) != len(by[tid].get("rows") or []):
            out.append(f"meta.{tid} is {meta.get(tid)}, table {tid!r} has {len(by[tid].get('rows') or [])} rows")
    return out


def data_text(root: ET.Element) -> str:
    """The checked tables-browser.json text from a parsed tables file. BrowserDataError when it fails a check."""
    data = build(root)
    bad = problems(data)
    if bad:
        raise BrowserDataError("www/%s fails its checks:\n  %s" % (OUT_REL, "\n  ".join(bad)))
    return json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n"


def page_text(raw: bytes, root: ET.Element, www: Path | str = WWW) -> str:
    """The tables file page in `www` with its marked regions filled from the tables file. BrowserDataError when the
    page and the file disagree (tables_page.PageError)."""
    try:
        return tables_page.fill((Path(www) / PAGE_REL).read_text(encoding="utf-8"), tables_page.facts(raw, root))
    except tables_page.PageError as exc:
        raise BrowserDataError(str(exc)) from exc


def outputs(www: Path | str = WWW, src: Path | str = SRC) -> dict[Path, str]:
    """{path under www: text} for the browser data and the filled page, read from `www`."""
    raw, root = load(src)
    return {OUT_REL: data_text(root), PAGE_REL: page_text(raw, root, www)}


def stale(www: Path | str = WWW, src: Path | str = SRC) -> list[Path]:
    """The committed page under `www` when its text differs from what the tables file gives (the data is not
    committed, so it is never stale: data_text() builds and checks it)."""
    raw, root = load(src)
    data_text(root)
    page = Path(www) / PAGE_REL
    return [] if page.is_file() and page.read_text(encoding="utf-8") == page_text(raw, root, www) else [PAGE_REL]


def write(www: Path | str = WWW, src: Path | str = SRC) -> dict[Path, str]:
    out = outputs(www, src)
    for rel, text in out.items():
        (Path(www) / rel).parent.mkdir(parents=True, exist_ok=True)
        (Path(www) / rel).write_text(text, encoding="utf-8")
    return out


def write_page(www: Path | str, src: Path | str = SRC) -> None:
    """Fill the tables file page in `www` (the site build's copy); the data is built on its own (site_views)."""
    raw, root = load(src)
    (Path(www) / PAGE_REL).write_text(page_text(raw, root, www), encoding="utf-8")


def view(src: Path | str = SRC) -> str:
    """The browser data for the site build and the local preview (site_views.VIEWS)."""
    return data_text(load(src)[1])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write www/%s and www/%s from the tables file." % (PAGE_REL, OUT_REL))
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the page is stale or the data fails a check; write nothing")
    args = parser.parse_args(argv)      # an unknown argument is a usage error (exit 2), never a write run
    if not args.check:
        paths.exit_if_overridden(Path(__file__).name)
    try:
        if args.check:
            if stale():
                print("www/%s is stale; run python3 www/scripts/build_tables_browser.py and commit it" % PAGE_REL,
                      file=sys.stderr)
                return 1
            print("tables-file.html is current and tables-browser.json builds and passes its checks")
            return 0
        done = write()
    except BrowserDataError as err:
        print(err, file=sys.stderr)
        return 1
    for rel, text in done.items():
        print("wrote www/%s (%d bytes)" % (rel, len(text.encode())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
