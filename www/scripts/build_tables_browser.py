#!/usr/bin/env python3
"""Write the tables file page and its browser data from the JMRI tables file.

    python3 www/scripts/build_tables_browser.py          # write
    python3 www/scripts/build_tables_browser.py --check  # exit 1 if either is stale

Writes www/data/tables-browser.json (the browser's rows) and fills the marked
regions of www/behind/tables-file.html (its numbers, version and excerpts; see
tables_page.py). prepare_github_pages.py runs the same fill on every site build.

Allowlist only: each table lists the fields it emits. File history,
connections and paths are never read into the output. Output is in file order
with no timestamps.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tables_page  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "jmri/layouts/hart/output/tables.xml"
OUT_REL = Path("data/tables-browser.json")
PAGE_REL = Path("behind/tables-file.html")
WWW = ROOT / "www"
OUT = WWW / OUT_REL

NOTE = "Generated by www/scripts/build_tables_browser.py from the tables file; do not edit by hand."

MAST_RE = re.compile(r"\$(shsm|vsm):([^:]+):([^(]+)\(")


def direct(root, manager, child):
    """Direct children `child` of every <manager> element (not nested ones)."""
    return [c for m in root.findall(manager) for c in m if c.tag == child]


def names(e):
    return e.findtext("systemName", ""), e.findtext("userName", "") or ""


def yes(v):
    return "yes" if (v or "").strip().lower() == "yes" else "no"


def note(e):
    """An object's comment. JMRI stores it as a child element or an attribute."""
    return (e.findtext("comment") or e.get("comment") or "").strip()


def load(src=SRC):
    raw = Path(src).read_bytes()
    return raw, ET.fromstring(raw)


def build(r):
    tables = []

    def add(tid, label, cols, rows):
        tables.append({"id": tid, "label": label,
                       "cols": [{"k": k, "label": l} for k, l in cols], "rows": rows})

    # Sensors: MQTT or internal, from the system name prefix.
    rows = []
    for e in direct(r, "sensors", "sensor"):
        s, u = names(e)
        rows.append([s, u, "MQTT" if s.startswith("M2S") else "Internal", note(e)])
    add("sensors", "Sensors", [("sys", "System name"), ("user", "User name"), ("kind", "Kind"), ("note", "Comment")], rows)

    rows = []
    for e in direct(r, "turnouts", "turnout"):
        s, u = names(e)
        fb = {"TWOSENSOR": "Two sensors", "DIRECT": "Direct", "ONESENSOR": "One sensor",
              "MONITORING": "Monitoring", "DELAYED": "Delayed", "EXACT": "Exact",
              "INDIRECT": "Indirect"}.get(e.get("feedback", ""), e.get("feedback", ""))
        sens = ", ".join(x for x in (e.get("sensor1"), e.get("sensor2")) if x)
        rows.append([s, u, fb, sens, note(e)])
    add("turnouts", "Turnouts", [("sys", "System name"), ("user", "User name"),
                                 ("fb", "Feedback"), ("sens", "Feedback sensors"), ("note", "Comment")], rows)

    rows = [list(names(e)) + [note(e)] for e in direct(r, "memories", "memory")]
    add("memories", "Memories", [("sys", "System name"), ("user", "User name"), ("note", "Comment")], rows)

    rows = []
    for e in direct(r, "signalheads", "signalhead"):
        s, u = names(e)
        cls = e.get("class", "").rsplit(".", 1)[-1]
        rows.append([s, u, "Virtual" if cls.startswith("Virtual") else cls.replace("Xml", ""), note(e)])
    add("heads", "Signal heads", [("sys", "System name"), ("user", "User name"), ("type", "Head type"), ("note", "Comment")], rows)

    rows = []
    for e in [c for m in r.findall("signalmasts") for c in m if c.tag in ("signalmast", "virtualsignalmast")]:
        s, u = names(e)
        m = MAST_RE.search(s)
        kind = ("On heads" if m.group(1) == "shsm" else "Virtual") if m else ""
        rows.append([s, u, kind, m.group(2) if m else "", m.group(3) if m else "", note(e)])
    add("masts", "Signal masts", [("sys", "System name"), ("user", "User name"), ("kind", "Heads"),
                                  ("app", "Appearance system"), ("shape", "Mast type"), ("note", "Comment")], rows)

    # Blocks: the second, full pass only (the first pass lists names).
    rows = []
    for e in direct(r, "blocks", "block"):
        if len(e) <= 2:
            continue
        s, u = names(e)
        rows.append([s, u, e.get("length", ""), e.findtext("occupancysensor", "") or "",
                     len(e.findall("path")), note(e)])
    add("blocks", "Blocks", [("sys", "System name"), ("user", "User name"), ("len", "Length (mm)"),
                             ("occ", "Occupancy sensor"), ("paths", "Paths"), ("note", "Comment")], rows)

    rows = []
    for e in direct(r, "layoutblocks", "layoutblock"):
        s, u = names(e)
        rows.append([s, u, e.get("occupancysensor", "")])
    add("layoutblocks", "Layout blocks", [("sys", "System name"), ("user", "User name"),
                                          ("occ", "Occupancy sensor")], rows)

    rows = []
    for e in direct(r, "sections", "section"):
        s, u = names(e)
        ct = {"signalmastlogic": "From a mast pair", "userdefined": "Defined by hand"}.get(
            e.get("creationtype", ""), e.get("creationtype", ""))
        rows.append([s, u, ct, len(e.findall("blockentry"))])
    add("sections", "Sections", [("sys", "System name"), ("user", "User name"),
                                 ("made", "How made"), ("blocks", "Blocks listed")], rows)

    rows = []
    for e in direct(r, "transits", "transit"):
        s, u = names(e)
        rows.append([s, u, len(e.findall("transitsection"))])
    add("transits", "Transits", [("sys", "System name"), ("user", "User name"), ("secs", "Sections")], rows)

    rows = []
    for e in direct(r, "routes", "route"):
        s, u = names(e)
        rows.append([s, u, e.get("controlTurnout", ""), len(e.findall("routeOutputTurnout")), note(e)])
    add("routes", "Routes", [("sys", "System name"), ("user", "User name"),
                             ("ctl", "Control turnout"), ("outs", "Turnout settings"), ("note", "Comment")], rows)

    rows = []
    for e in direct(r, "signalmastlogics", "signalmastlogic"):
        src = e.findtext("sourceSignalMast", "")
        for d in e.findall("destinationMast"):
            rows.append([src, d.findtext("destinationSignalMast", ""), yes(d.findtext("enabled")), note(d)])
    n_src = len(direct(r, "signalmastlogics", "signalmastlogic"))
    add("sml", "Signal Mast Logic", [("src", "Source mast"), ("dst", "Destination mast"),
                                     ("on", "Enabled"), ("note", "Comment")], rows)

    rows = []
    for ee in r.findall("entryexitpairs"):
        for p in ee.findall("layoutPanel"):
            for s in p.findall("source"):
                for d in s.findall("destination"):
                    rows.append([s.get("item", ""), d.get("item", "")])
    add("entryexit", "Entry/Exit", [("src", "Source"), ("dst", "Destination")], rows)

    rows = []
    for e in direct(r, "logixs", "logix"):
        s, u = names(e)
        rows.append([s, u, yes(e.get("enabled")), len(e.findall("logixConditional"))])
    add("logix", "Logix", [("sys", "System name"), ("user", "User name"),
                           ("on", "Enabled"), ("conds", "Conditionals")], rows)

    rows = []
    for e in direct(r, "LogixNGs", "LogixNG"):
        s, u = names(e)
        cn = e.find("ConditionalNGs")
        rows.append([s, u, yes(e.get("enabled")), len(cn.findall("systemName")) if cn is not None else 0])
    add("logixng", "LogixNG", [("sys", "System name"), ("user", "User name"),
                               ("on", "Enabled"), ("conds", "ConditionalNGs")], rows)

    by = {t["id"]: len(t["rows"]) for t in tables}
    meta = {"sensors": by["sensors"], "turnouts": by["turnouts"], "memories": by["memories"],
            "heads": by["heads"], "masts": by["masts"], "smlSources": n_src,
            "smlDestinations": by["sml"], "blocks": by["blocks"], "layoutBlocks": by["layoutblocks"],
            "sections": by["sections"], "transits": by["transits"], "routes": by["routes"],
            "entryExit": by["entryexit"], "logix": by["logix"], "logixng": by["logixng"]}
    return {"_note": NOTE, "meta": meta, "tables": tables}


def outputs(www=WWW, src=SRC):
    """{path under www: text} for the browser data and the filled page, read from `www`."""
    raw, root = load(src)
    data = json.dumps(build(root), ensure_ascii=False, separators=(",", ":")) + "\n"
    page = tables_page.fill((Path(www) / PAGE_REL).read_text(encoding="utf-8"), tables_page.facts(raw, root))
    return {OUT_REL: data, PAGE_REL: page}


def stale(www=WWW, src=SRC):
    """Paths under `www` whose text differs from what the tables file gives."""
    return [rel for rel, text in outputs(www, src).items()
            if not (Path(www) / rel).exists() or (Path(www) / rel).read_text(encoding="utf-8") != text]


def write(www=WWW, src=SRC):
    out = outputs(www, src)
    for rel, text in out.items():
        (Path(www) / rel).write_text(text, encoding="utf-8")
    return out


def main():
    if "--check" in sys.argv:
        bad = stale()
        if bad:
            names = " and ".join("www/%s" % p for p in bad)
            sys.exit("%s %s stale; run python3 www/scripts/build_tables_browser.py"
                     % (names, "is" if len(bad) == 1 else "are"))
        print("tables-browser.json and tables-file.html are current")
        return
    for rel, text in write().items():
        print("wrote www/%s (%d bytes)" % (rel, len(text.encode())))


if __name__ == "__main__":
    main()
