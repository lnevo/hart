def load_roster() -> dict[str, dict]:
    root = ET.parse(ROSTER_XML).getroot()
    out: dict[str, dict] = {}
    for el in root.findall("./cars/car"):
        rid = el.get("id", "")
        out[rid] = {
            "roster_id": rid,
            "roster_road": el.get("roadName", ""),
            "road_number": el.get("roadNumber", ""),
            "car_type": el.get("type", ""),
            "roster_length_ft": el.get("length", ""),
            "roster_weight_oz": el.get("weight", ""),
            "roster_weight_tons": el.get("weightTons", ""),
        }
    return out


def _merge_notes(existing: str, new: str) -> str:
    parts: list[str] = []
    for chunk in (existing, new):
        for p in chunk.split(";"):
            p = p.strip()
            if p and p not in parts:
                parts.append(p)
    return "; ".join(parts)


def apply_review() -> None:
    roster = load_roster()
    rows: list[dict] = []

    with METADATA_CSV.open(newline="") as f:
        for row in csv.DictReader(f):
            src = row.get("source_image", "")
            review = VISUAL.get(src)
            if not review:
                rows.append(row)
                continue

            for key, val in review.items():
                if key == "notes":
                    continue
                row[key] = val

            rid = row.get("roster_id", "").strip()
            if rid and rid in roster:
                car = roster[rid]
                row["roster_id"] = rid
                row["roster_road"] = car["roster_road"]
                row["roster_length_ft"] = car["roster_length_ft"]
                row["roster_weight_oz"] = car["roster_weight_oz"]
                row["roster_weight_tons"] = car["roster_weight_tons"]
                if not row.get("road_number"):
                    row["road_number"] = car["road_number"]
                if not row.get("car_type"):
                    row["car_type"] = car["car_type"]
                road = car["roster_road"]
                marks = ROAD_DISPLAY.get(road, road)
                row["reporting_marks"] = marks
                row["road_name"] = marks
            elif row.get("reporting_marks"):
                row["road_name"] = row["reporting_marks"]

            if review.get("notes"):
                row["notes"] = _merge_notes(row.get("notes", ""), review["notes"])

            rows.append(row)

    for row in rows:
        ctype = (row.get("car_type") or "").strip()
        if is_locomotive_row(row) or ctype in ("Locomotive", "Streetcar"):
            continue
        assign_freight_roster_id(row)

    with METADATA_CSV.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        w.writeheader()
        for row in rows:
            w.writerow({c: row.get(c, "") for c in CSV_COLUMNS})

    matched = sum(1 for r in rows if r.get("roster_id"))
    has_marks = sum(1 for r in rows if r.get("reporting_marks"))
    has_type = sum(1 for r in rows if r.get("car_type"))
    has_color = sum(1 for r in rows if r.get("color"))
    dups = sum(1 for r in rows if r.get("duplicate_of"))
    print(f"Wrote {METADATA_CSV} ({len(rows)} rows)")
    print(f"  roster matches: {matched}")
    print(f"  reporting marks: {has_marks}")
    print(f"  car_type filled: {has_type}")
    print(f"  color filled:    {has_color}")
    print(f"  duplicates:      {dups}")


def main() -> int:
    apply_review()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
