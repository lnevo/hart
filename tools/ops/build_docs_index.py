#!/usr/bin/env python3
"""build_docs_index.py

Write docs/INDEX.md: every document under docs/, newest change first.

    python3 tools/ops/build_docs_index.py            write it
    python3 tools/ops/build_docs_index.py --check    exit 1 when it lists other documents than the tracked ones
                                                     (dates are not compared; a shallow clone has none)
"""
from __future__ import annotations

import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
TOOLING = (".py", ".sh", ".scad", ".stl", ".3mf", ".gitignore")
SKIP = ("docs/wiring/imported/", "docs/INDEX.md")


def tracked() -> list[str]:
    out = subprocess.check_output(["git", "ls-files", "-z", "docs"], cwd=ROOT, text=True)
    return [p for p in out.split("\0") if p and not p.startswith(SKIP) and not p.endswith(TOOLING)]


def last_changed() -> dict[str, str]:
    out = subprocess.check_output(
        ["git", "log", "--name-only", "--format=%x00%ad", "--date=short", "-z", "--", "docs"],
        cwd=ROOT,
        text=True,
    )
    dates: dict[str, str] = {}
    current = ""
    for chunk in out.split("\0"):
        chunk = chunk.strip()
        if len(chunk) == 10 and chunk[4] == "-":
            current = chunk
        elif chunk:
            dates.setdefault(chunk, current)
    return dates


def doc_link(path: str) -> str:
    """Link from docs/INDEX.md to a docs/ file, with every space and non-ASCII character encoded."""
    return quote(path.removeprefix("docs/"))


def render(paths: list[str], dates: dict[str, str]) -> str:
    """The text of docs/INDEX.md for these tracked documents, each with its last change date from `dates`."""
    groups: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for path in paths:
        area = path.split("/")[1] if path.count("/") > 1 else "general"
        groups[area].append((dates.get(path, ""), path))
    lines = ["# Document index", "", "Generated by `tools/ops/build_docs_index.py`. Newest first in each area.", ""]
    for area in sorted(groups):
        lines += [f"## {area}", "", "| Changed | Document | Type |", "|---|---|---|"]
        for changed, path in sorted(groups[area], key=lambda r: (r[0], r[1]), reverse=True):
            name = Path(path).name
            link = doc_link(path)
            lines.append(f"| {changed} | [{name}]({link}) | {Path(path).suffix.lstrip('.')} |")
        lines.append("")
    return "\n".join(lines)


def listed(text: str) -> set[tuple[str, str]]:
    """The (area, row without its date) pairs of an index text: which documents it lists, not when they changed."""
    area, rows = "", set()
    for line in text.splitlines():
        if line.startswith("## "):
            area = line[3:]
        elif line.startswith("| ") and "](" in line:
            rows.add((area, line.split("|", 2)[2].strip()))
    return rows


def check() -> int:
    """0 when docs/INDEX.md lists exactly the tracked documents. Dates are not compared: a shallow clone (CI) has
    no history to date them from, and a date moves with every edit."""
    paths = tracked()
    have = listed((ROOT / "docs/INDEX.md").read_text(encoding="utf-8")) if (ROOT / "docs/INDEX.md").is_file() else set()
    want = listed(render(paths, {}))
    if have == want:
        print(f"docs/INDEX.md lists all {len(paths)} documents")
        return 0
    print("build_docs_index.py: docs/INDEX.md is out of date; run python3 tools/ops/build_docs_index.py and commit it", file=sys.stderr)
    for label, rows in (("missing", want - have), ("not tracked", have - want)):
        for area, row in sorted(rows)[:10]:
            print(f"  {label}: {area}: {row}", file=sys.stderr)
        if len(rows) > 10:
            print(f"  ... and {len(rows) - 10} more {label}", file=sys.stderr)
    return 1


def main(argv: list[str]) -> int:
    if {"-h", "--help"} & set(argv):     # help wins over any other argument: it only prints
        print(__doc__ or "build_docs_index.py [--check]")      # python -OO strips the docstring
        return 0
    if argv == ["--check"]:
        return check()
    if argv:            # a typo must not fall through to a rewrite
        bad = argv[1] if argv[0] == "--check" else argv[0]
        print(f"build_docs_index.py: unknown argument {bad!r}; the only option is --check, alone (--help for more)", file=sys.stderr)
        return 2
    paths = tracked()
    text = render(paths, last_changed())
    (ROOT / "docs/INDEX.md").write_text(text, encoding="utf-8")
    print(f"wrote docs/INDEX.md: {len(paths)} documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
