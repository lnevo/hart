#!/usr/bin/env python3
"""Write docs/INDEX.md: every document under docs/, newest change first."""
from __future__ import annotations

import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = ("docs/wiring/imported/", "docs/wiring/scripts/", "docs/wiring/lcos/build_", "docs/INDEX.md")


def tracked() -> list[str]:
    out = subprocess.check_output(["git", "ls-files", "-z", "docs"], cwd=ROOT, text=True)
    return [p for p in out.split("\0") if p and not p.startswith(SKIP)]


def last_changed() -> dict[str, str]:
    out = subprocess.check_output(
        ["git", "log", "--name-only", "--format=%x00%ad", "--date=short", "-z", "--", "docs"],
        cwd=ROOT,
        text=True,
    )
    dates: dict[str, str] = {}
    current = ""
    for chunk in out.split("\0"):
        chunk = chunk.strip()
        if len(chunk) == 10 and chunk[4] == "-":
            current = chunk
        elif chunk:
            dates.setdefault(chunk, current)
    return dates


def main() -> int:
    dates = last_changed()
    groups: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for path in tracked():
        area = path.split("/")[1] if path.count("/") > 1 else "general"
        groups[area].append((dates.get(path, ""), path))
    lines = ["# Document index", "", "Generated by `tools/ops/build_docs_index.py`. Newest first in each area.", ""]
    for area in sorted(groups):
        lines += [f"## {area}", "", "| Changed | Document | Type |", "|---|---|---|"]
        for changed, path in sorted(groups[area], key=lambda r: (r[0], r[1]), reverse=True):
            name = Path(path).name
            link = path[len("docs/"):].replace(" ", "%20")
            lines.append(f"| {changed} | [{name}]({link}) | {Path(path).suffix.lstrip('.')} |")
        lines.append("")
    (ROOT / "docs/INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote docs/INDEX.md: {sum(map(len, groups.values()))} documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
