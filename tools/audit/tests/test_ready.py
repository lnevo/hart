ROOT = Path(__file__).resolve().parents[3]


def load(path: Path, name: str) -> Any:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclasses look the module up by name
    spec.loader.exec_module(module)
    return module


R = load(ROOT / "tools/agent/ready.py", "hart_ready_test")
NAME_CHECK = ROOT / "ops/hart-ops/card_pipeline/private_name.py"


def sh(*args: str, cwd: Path) -> str:
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


class FakeGitHub:
    """Answers gh pr view and gh pr create; records every call."""

    def __init__(self, open_pr: bool = False) -> None:
        self.calls: list[list[str]] = []
        self.bodies: list[str] = []
        self.made = open_pr

    def __call__(self, repo: Path, args: Sequence[str]) -> subprocess.CompletedProcess[str]:
        self.calls.append(list(args))
        if args[:2] == ["pr", "create"]:
            self.bodies.append(Path(args[args.index("--body-file") + 1]).read_text())
            self.made = True
            return subprocess.CompletedProcess(args, 0, "https://example.invalid/pull/7\n", "")
        if self.made:
            return subprocess.CompletedProcess(
                args, 0, json.dumps({"number": 7, "url": "https://example.invalid/pull/7", "state": "OPEN"}), "")
        return subprocess.CompletedProcess(args, 1, "", "no pull requests found")


class ReadyCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(os.path.realpath(tempfile.mkdtemp()))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        origin, self.main = self.tmp / "origin.git", self.tmp / "main"
        sh("git", "init", "-q", "--bare", "-b", "main", str(origin), cwd=self.tmp)
        sh("git", "clone", "-q", str(origin), str(self.main), cwd=self.tmp)
        self.configure(self.main)
        sh("git", "checkout", "-q", "-b", "main", cwd=self.main)
        (self.main / "ops/hart-ops/card_pipeline").mkdir(parents=True)
        shutil.copy(NAME_CHECK, self.main / "ops/hart-ops/card_pipeline/private_name.py")
        (self.main / "a.txt").write_text("".join(f"{i}\n" for i in range(1, 9)))
        (self.main / "b.txt").write_text("b\n")
        (self.main / ".gitignore").write_text(".claude/worktrees/\n")
        sh("git", "add", ".", cwd=self.main)
        sh("git", "commit", "-q", "-m", "init", cwd=self.main)
        sh("git", "push", "-q", "-u", "origin", "main", cwd=self.main)
        self.wt = self.main / ".claude/worktrees/topic"
        sh("git", "worktree", "add", "-q", "-b", "agent/claude/topic", str(self.wt), "origin/main", cwd=self.main)
        self.attribution = self.tmp / "attribution.json"
        self.attribution.write_text(json.dumps({"commit": ["Co-Authored-By: Test <t@example.invalid>"],
                                                "pr": ["Generated by a test"]}))
        env = mock.patch.dict(os.environ, {R.ATTRIBUTION_ENV: str(self.attribution)})
        env.start()
        self.addCleanup(env.stop)
        self.gh = FakeGitHub()
        self.remote_calls: list[Path] = []
        self.remote_text = "--- unit ok\nALL PASSED\n"
        self.kind = "full: code changed"
        self.gate = "remote: a.txt feeds tools/plan.py, which reads ext:plan (check plan)"

    @staticmethod
    def configure(repo: Path) -> None:
        sh("git", "config", "user.email", "t@example.invalid", cwd=repo)
        sh("git", "config", "user.name", "t", cwd=repo)

    def remote(self, repo: Path, log: Path) -> int:
        self.remote_calls.append(log)
        log.write_text(self.remote_text)
        return 0

    def tools(self, **over: Any) -> Any:
        made = dict(remote=self.remote, gh_run=self.gh, pr_kind=lambda repo: self.kind,
                    private_gate=lambda repo: self.gate,
                    regenerate=(R.Step("gen", ("python3", "-c", "open('gen.txt','w').write('made\\n')"),
                                       ("gen.txt",)),),
                    checks=(R.Step("ok", ("true",)),), log_dir=self.tmp / "logs", say=lambda text: None)
        made.update(over)
        return R.Tools(**made)

    def change(self, name: str = "a.txt", text: str = "changed\n") -> None:
        (self.wt / name).write_text(text)

    def ship(self, files: tuple[str, ...] = ("a.txt",), msg: str = "fix: a", body: str = "What changed.",
             remote: bool = False, **over: Any) -> Any:
        return R.ready(self.wt, R.Request(files, msg, "", body, remote=remote), self.tools(**over))

    def main_commit(self, name: str, text: str) -> None:
        (self.main / name).write_text(text)
        sh("git", "commit", "-q", "-am", f"main: {name}", cwd=self.main)
        sh("git", "push", "-q", "origin", "main", cwd=self.main)


class Ships(ReadyCase):
    def test_a_full_change_commits_by_name_pushes_runs_remote_and_opens_the_pr(self) -> None:
        self.change()
        (self.wt / "b.txt").write_text("left alone\n")
        shipped = self.ship()
        self.assertEqual(7, shipped.pr)
        self.assertEqual(sh("git", "rev-parse", "HEAD", cwd=self.wt), shipped.head)
        self.assertEqual(shipped.head, sh("git", "rev-parse", "origin/agent/claude/topic", cwd=self.wt))
        log = sh("git", "log", "--format=%B", "-n", "2", cwd=self.wt)
        self.assertIn("fix: a", log)
        self.assertIn("chore: regenerate gen.txt", log)
        self.assertEqual(2, log.count("Co-Authored-By: Test"))
        committed = sh("git", "diff", "--name-only", "origin/main", "HEAD", cwd=self.wt).split()
        self.assertEqual(["a.txt", "gen.txt"], committed)
        self.assertIn("b.txt", sh("git", "status", "--porcelain", cwd=self.wt))
        self.assertEqual([shipped.log], self.remote_calls)
        self.assertTrue(str(shipped.log).endswith(f"agent-claude-topic-{shipped.head[:12]}.log"))
        self.assertTrue(all(c[:2] in (["pr", "view"], ["pr", "create"]) for c in self.gh.calls), self.gh.calls)
        self.assertIn("What changed.", self.gh.bodies[0])
        self.assertIn("Generated by a test", self.gh.bodies[0])

    def test_a_light_change_skips_the_remote_and_says_so(self) -> None:
        self.kind = "light: map presets"
        self.change()
        shipped = self.ship()
        self.assertIsNone(shipped.log)
        self.assertEqual([], self.remote_calls)
        self.assertIn("`make pr-kind` printed `light`", self.gh.bodies[0])

    def test_an_open_pr_is_printed_not_made_again(self) -> None:
        self.gh.made = True
        self.change()
        self.assertEqual(7, self.ship().pr)
        self.assertFalse(any(c[:2] == ["pr", "create"] for c in self.gh.calls))

    def test_a_remote_run_without_all_passed_stops_before_the_pr(self) -> None:
        self.remote_text = "--- unit FAILED\nFAILED\n"
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "ALL PASSED"):
            self.ship()
        self.assertFalse(any(c[:2] == ["pr", "create"] for c in self.gh.calls))

    def test_a_failed_check_stops_before_the_push(self) -> None:
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "broken failed"):
            self.ship(checks=(R.Step("broken", ("false",)),))
        self.assertEqual("", sh("git", "ls-remote", "origin", "agent/claude/topic", cwd=self.wt))


class Gates(ReadyCase):
    """Which gate a change gets: make remote when a changed path feeds a check that reads private files, else
    GitHub's check on a draft PR; docs and light changes as before; REMOTE=1 forces the remote run."""

    def creates(self) -> list[list[str]]:
        return [c for c in self.gh.calls if c[:2] == ["pr", "create"]]

    def test_a_private_read_runs_the_remote_and_opens_a_ready_pr(self) -> None:
        said: list[str] = []
        self.change()
        shipped = self.ship(say=said.append)
        self.assertEqual(1, len(self.remote_calls))
        self.assertEqual((self.gate, False), (shipped.gate, shipped.draft))
        self.assertIn(self.gate, said)
        self.assertNotIn("--draft", self.creates()[0])

    def test_no_private_read_skips_the_remote_and_opens_a_draft(self) -> None:
        said: list[str] = []
        self.gate = "github: no changed path feeds a check step that reads private files (ext:plan)"
        self.change()
        shipped = self.ship(say=said.append)
        self.assertEqual([], self.remote_calls)
        self.assertIsNone(shipped.log)
        self.assertTrue(shipped.draft)
        self.assertIn("--draft", self.creates()[0])
        self.assertIn(R.DRAFT_NOTE, self.gh.bodies[0])
        gate_lines = [line for line in said if line.startswith("GitHub gate: ")]
        self.assertEqual(1, len(gate_lines), said)
        self.assertIn("no changed path feeds a check step that reads private files", gate_lines[0])

    def test_remote_1_forces_the_remote_run(self) -> None:
        self.gate = "github: nothing private"
        self.change()
        shipped = self.ship(remote=True)
        self.assertEqual(1, len(self.remote_calls))
        self.assertEqual(("remote: REMOTE=1 asks for it", False), (shipped.gate, shipped.draft))
        self.assertNotIn("--draft", self.creates()[0])

    def test_remote_1_forces_it_on_a_light_change_too(self) -> None:
        self.kind = "light: map presets"
        self.change()
        self.ship(remote=True)
        self.assertEqual(1, len(self.remote_calls))

    def test_docs_and_light_never_ask_the_private_gate_and_are_not_drafts(self) -> None:
        def never(_repo: Path) -> str:
            raise AssertionError("asked")
        for n, kind in enumerate(("docs: 1 changed path", "light: map presets")):
            with self.subTest(kind):
                self.kind = kind
                self.gh.made = False
                self.change(text=f"changed {n}\n")
                shipped = self.ship(private_gate=never)
                self.assertEqual(([], False), (self.remote_calls, shipped.draft))
                self.assertTrue(shipped.gate.startswith("no remote run: a " + kind.split(":")[0]), shipped.gate)

    def test_a_gate_line_with_no_verdict_runs_the_remote(self) -> None:
        self.gate = "Traceback (most recent call last):"
        self.change()
        shipped = self.ship()
        self.assertEqual(1, len(self.remote_calls))
        self.assertTrue(shipped.gate.startswith("remote: the private-reads check printed no verdict"))

    def test_a_private_gate_that_cannot_run_says_remote(self) -> None:
        # the scratch worktree has no tools/ci/changed_kind.py: python3 fails, and the gate fails toward the remote
        self.assertTrue(R.default_private_gate(self.wt).startswith("remote: changed_kind.py --private failed"))

    def test_a_name_with_u202f_is_staged_and_read_back_as_named(self) -> None:
        name = "Screenshot 12.52.19\u202fAM.txt"
        self.change(name, "odd\n")
        self.ship(files=(name,))
        committed = sh("git", "-c", "core.quotePath=false", "diff", "--name-only", "origin/main", "HEAD", cwd=self.wt)
        self.assertIn(name, committed.splitlines())
        self.assertIn(name, R.branch_files(self.wt))


class Reruns(ReadyCase):
    def test_the_same_command_runs_again_after_a_later_step_failed(self) -> None:
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "broken failed"):
            self.ship(checks=(R.Step("broken", ("false",)),))
        first = sh("git", "rev-parse", "HEAD", cwd=self.wt)
        shipped = self.ship()
        self.assertEqual(7, shipped.pr)
        self.assertIn(first, sh("git", "log", "--format=%H", cwd=self.wt).split())
        self.assertEqual(1, sh("git", "log", "--format=%s", "origin/main..HEAD", cwd=self.wt).count("fix: a"))

    def test_a_named_file_with_no_change_on_the_branch_still_fails(self) -> None:
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "b.txt: no change"):
            self.ship(("a.txt", "b.txt"))


class PrText(ReadyCase):
    def test_a_missing_body_stops_before_any_commit_or_push(self) -> None:
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "BODY"):
            self.ship(body="")
        self.assertEqual([], self.remote_calls)
        self.assertEqual("", sh("git", "log", "--format=%H", "origin/main..HEAD", cwd=self.wt))

    def test_a_missing_body_is_fine_when_the_pr_is_open(self) -> None:
        self.gh.made = True
        self.change()
        self.assertEqual(7, self.ship(body="").pr)

    def test_the_body_file_rule(self) -> None:
        inside = self.wt / "body.md"
        inside.write_text("What changed.\n")
        self.assertEqual("What changed.\n", R.read_body_file(self.wt, str(inside)))
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        (tmp / "body.txt").write_text("ok\n")
        self.assertEqual("ok\n", R.read_body_file(self.wt, str(tmp / "body.txt")))
        for path, why in ((self.wt / ".env.local", "never a private"), (self.wt / "key", "never a private"),
                          (Path.home() / ".ssh/id_rsa", "outside"), (self.wt / "missing.md", "cannot read")):
            with self.subTest(path=path):
                if path.parent == self.wt and path.name != "missing.md":
                    path.write_text("SECRET=1\n")
                with self.assertRaisesRegex(R.ReadyError, why):
                    R.read_body_file(self.wt, str(path))


class Branches(ReadyCase):
    def test_branch_renames_an_isolation_worktree_branch(self) -> None:
        sh("git", "branch", "-m", "worktree-agent-abc123", cwd=self.wt)
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "BRANCH=agent/claude/<topic>"):
            self.ship()
        shipped = R.ready(self.wt, R.Request(("a.txt",), "fix: a", "", "Body.", "agent/claude/renamed"), self.tools())
        self.assertEqual(7, shipped.pr)
        self.assertEqual("agent/claude/renamed", sh("git", "branch", "--show-current", cwd=self.wt))

    def test_branch_never_renames_another_branch_or_onto_one_that_exists(self) -> None:
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "only an isolation worktree"):
            R.ready(self.wt, R.Request(("a.txt",), "m", "", "B.", "agent/claude/x"), self.tools())
        sh("git", "branch", "-m", "worktree-agent-abc123", cwd=self.wt)
        sh("git", "branch", "agent/claude/taken", "origin/main", cwd=self.main)
        with self.assertRaisesRegex(R.ReadyError, "already exists"):
            R.ready(self.wt, R.Request(("a.txt",), "m", "", "B.", "agent/claude/taken"), self.tools())
        with self.assertRaisesRegex(R.ReadyError, "not agent/claude"):
            R.ready(self.wt, R.Request(("a.txt",), "m", "", "B.", "feature/x"), self.tools())


class Merges(ReadyCase):
    def test_main_changing_a_touched_file_is_merged_in(self) -> None:
        self.main_commit("a.txt", "".join(f"{i}\n" for i in ["one", *range(2, 9)]))
        self.change("a.txt", "".join(f"{i}\n" for i in [*range(1, 8), "eight"]))
        self.ship()
        parents = sh("git", "log", "-1", "--format=%P", "HEAD~1", cwd=self.wt).split()
        self.assertEqual(2, len(parents), "HEAD~1 is the merge of origin/main")
        self.assertEqual(sh("git", "rev-parse", "origin/main", cwd=self.wt), parents[1])
        self.assertEqual("gen.txt", sh("git", "show", "--name-only", "--format=", "HEAD", cwd=self.wt),
                         "the regeneration runs after the merge and is committed on top")

    def test_main_changing_another_file_is_not_merged(self) -> None:
        self.main_commit("b.txt", "b2\n")
        self.change()
        self.ship()
        merges = sh("git", "log", "--merges", "--format=%H", "origin/main..HEAD", cwd=self.wt)
        self.assertEqual("", merges)

    def test_a_conflict_aborts_the_merge_and_stops(self) -> None:
        self.main_commit("a.txt", "theirs\n")
        self.change("a.txt", "mine\n")
        with self.assertRaisesRegex(R.ReadyError, "conflicts in: a.txt"):
            self.ship()
        self.assertFalse((Path(sh("git", "rev-parse", "--git-dir", cwd=self.wt)) / "MERGE_HEAD").exists())


class Refuses(ReadyCase):
    def test_the_main_checkout(self) -> None:
        with self.assertRaisesRegex(R.ReadyError, "main checkout"):
            R.ready(self.main, R.Request(("a.txt",), "m"), self.tools())

    def test_a_branch_not_agent_claude(self) -> None:
        sh("git", "checkout", "-q", "-b", "feature/x", cwd=self.wt)
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "not agent/claude"):
            self.ship()

    def test_a_subfolder_and_a_worktree_elsewhere(self) -> None:
        (self.wt / "sub").mkdir()
        with self.assertRaisesRegex(R.ReadyError, "subfolder"):
            R.ready(self.wt / "sub", R.Request((), "m"), self.tools())
        other = self.tmp / "elsewhere"
        sh("git", "worktree", "add", "-q", "-b", "agent/claude/other", str(other), cwd=self.main)
        with self.assertRaisesRegex(R.ReadyError, "not an agent worktree"):
            R.ready(other, R.Request((), "m"), self.tools())

    def test_files_that_are_never_committed_by_name(self) -> None:
        (self.wt / ".env.local").write_text("X=1\n")
        (self.wt / "tools/cats/src-repo").mkdir(parents=True)
        (self.wt / "tools/cats/src-repo/x.java").write_text("x\n")
        (self.wt / "dir").mkdir()
        (self.wt / "dir/f.txt").write_text("f\n")
        for path, why in ((".env.local", "private file"), ("tools/cats/src-repo/x.java", "private file"),
                          ("dir", "directory"), ("b.txt", "no change"), ("../x", "outside")):
            with self.subTest(path=path):
                with self.assertRaisesRegex(R.ReadyError, why):
                    self.ship((path,))
        self.assertEqual("", sh("git", "diff", "--cached", "--name-only", cwd=self.wt))

    def test_a_staged_file_not_named(self) -> None:
        (self.wt / "b.txt").write_text("staged\n")
        sh("git", "add", "b.txt", cwd=self.wt)
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "already staged but not in FILES: b.txt"):
            self.ship()

    def test_no_attribution_lines(self) -> None:
        self.attribution.unlink()
        self.change()
        with self.assertRaisesRegex(R.ReadyError, "no attribution lines"):
            self.ship()

    def test_the_private_name_in_the_text(self) -> None:
        self.change()
        with mock.patch.object(R, "private_name_check", lambda repo: lambda text: "NAME" in text):
            with self.assertRaisesRegex(R.ReadyError, "private name"):
                self.ship(msg="fix: NAME")
            with self.assertRaisesRegex(R.ReadyError, "private name"):
                self.ship(body="about NAME")
        self.assertFalse(any(c[:2] == ["pr", "create"] for c in self.gh.calls))

    def test_gh_beyond_view_and_create(self) -> None:
        tools = self.tools()
        for args in (["pr", "merge", "7"], ["pr", "close", "7"], ["api", "-X", "PUT", "x"], ["pr", "edit", "7"]):
            with self.subTest(args=args):
                with self.assertRaisesRegex(R.ReadyError, "does not run gh"):
                    tools.gh(self.wt, args)
        self.assertEqual([], self.gh.calls)

    def test_a_push_to_main(self) -> None:
        with self.assertRaisesRegex(R.ReadyError, "main"):
            R.push(self.wt, "main")
        self.assertEqual(sh("git", "rev-parse", "origin/main", cwd=self.main),
                         sh("git", "ls-remote", "origin", "refs/heads/main", cwd=self.main).split()[0])


